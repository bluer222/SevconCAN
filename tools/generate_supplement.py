#!/usr/bin/env python3
"""Preserve missing Gen4 parameter definitions from a pinned Sevcon DCF.

No existing bundled definition or vehicle-specific ParameterValue is copied.
Run with --check to verify the packaged supplement has not become stale.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sevcon_can.od import Record, bundled_eds_path, load_eds

SOURCE = ROOT / "specs/od/Gen4-AC24ls-rev0x00010017.dcf"
OUT = ROOT / "src/sevcon_can/data/Gen4-supplement.eds"


def render() -> str:
    base = load_eds(bundled_eds_path())
    source = load_eds(SOURCE)
    known = {var.key for var in base.variables()}
    missing = {var.key for var in source.variables() if var.key not in known}
    indices = {index for index, _ in missing}
    result = ["; Generated by tools/generate_supplement.py; do not edit.",
              "; Optional definitions from a different Gen4 firmware, not installed-device evidence.",
              "; Existing Gen4.eds definitions take precedence; no vehicle ParameterValue is copied."]
    blocks = re.split(r"(?m)(?=^\[)", SOURCE.read_text(encoding="latin-1"))
    for block in blocks:
        match = re.match(r"\[([0-9a-fA-F]{4})(?:sub([0-9a-fA-F]+))?\]", block)
        if not match:
            continue
        index = int(match[1], 16)
        if index not in indices:
            continue
        sub = int(match[2], 16) if match[2] else None
        if sub is not None and (index, sub) not in missing:
            continue
        if sub is None and index in base.objects and not isinstance(base[index], Record):
            continue
        lines = [line for line in block.strip().splitlines()
                 if not line.startswith("ParameterValue=")]
        lines.extend([f";SEVCONFIELD SUPPLEMENTAL_SOURCE={SOURCE.name}",
                      f";SEVCONFIELD FIRMWARE_PRODUCT={source.device_info['ProductNumber']}",
                      f";SEVCONFIELD FIRMWARE_REVISION={source.device_info['RevisionNumber']}",
                      ";SEVCONFIELD FIRMWARE_DEPENDENT=TRUE"])
        result.extend(["", *lines])
    return "\n".join(result) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="latin-1") != expected:
            print("Gen4-supplement.eds is stale; run tools/generate_supplement.py")
            return 1
        print("Gen4-supplement.eds up to date")
    else:
        OUT.write_text(expected, encoding="latin-1")
        print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
